import React, { useState } from 'react';
import { AuditResponse } from '../../types';
import { X, Copy, Check, Download, FileText } from 'lucide-react';

interface ReportPreviewModalProps {
  audit: AuditResponse;
  reportMarkdown: string;
  isOpen: boolean;
  onClose: () => void;
}

export const ReportPreviewModal: React.FC<ReportPreviewModalProps> = ({
  audit,
  reportMarkdown,
  isOpen,
  onClose
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const handleCopy = () => {
    navigator.clipboard.writeText(reportMarkdown);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([reportMarkdown], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `audit_report_${audit.audit_id}.md`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-in fade-in duration-150">
      <div className="bg-[#15181e] border border-zinc-800 rounded-xl w-full max-w-4xl max-h-[90vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="p-4 border-b border-zinc-800 flex items-center justify-between bg-[#171a22]">
          <div className="flex items-center gap-2.5">
            <div className="p-1.5 rounded bg-zinc-800 text-zinc-300">
              <FileText className="w-4 h-4" />
            </div>
            <div>
              <h2 className="text-sm font-semibold text-zinc-100">
                Audit Dossier &amp; Export Report
              </h2>
              <p className="text-[11px] text-zinc-500 font-mono">
                Audit ID: {audit.audit_id}
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="px-3 py-1.5 rounded bg-zinc-900 hover:bg-zinc-800 text-zinc-300 text-xs font-medium border border-zinc-700/80 flex items-center gap-1.5 transition"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied' : 'Copy Markdown'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="px-3 py-1.5 rounded bg-zinc-200 hover:bg-white text-zinc-900 text-xs font-semibold flex items-center gap-1.5 transition"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download .md</span>
            </button>
            <button
              onClick={onClose}
              className="p-1.5 rounded text-zinc-400 hover:text-white hover:bg-zinc-800 transition ml-1"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>

        {/* Executive Summary Metrics Strip */}
        {audit.summary && (
          <div className="px-5 py-2.5 bg-[#12141a] border-b border-zinc-800/80 grid grid-cols-2 sm:grid-cols-4 gap-4 text-xs font-mono">
            <div>
              <span className="text-zinc-500 text-[11px]">Trust Score:</span>{' '}
              <strong className="text-zinc-200">{Math.round(audit.summary.trust_score)}%</strong>
            </div>
            <div>
              <span className="text-zinc-500 text-[11px]">Risk:</span>{' '}
              <strong className="uppercase text-amber-400">{audit.summary.risk_level}</strong>
            </div>
            <div>
              <span className="text-zinc-500 text-[11px]">Claims:</span>{' '}
              <strong className="text-zinc-200">{audit.summary.total_claims}</strong>
            </div>
            <div>
              <span className="text-zinc-500 text-[11px]">Contradictions:</span>{' '}
              <strong className="text-rose-400">{audit.summary.contradicted_claims}</strong>
            </div>
          </div>
        )}

        {/* Markdown Content Viewer */}
        <div className="p-5 overflow-y-auto flex-1 font-mono text-xs text-zinc-300 leading-relaxed bg-[#101216] select-text">
          <pre className="whitespace-pre-wrap font-mono">{reportMarkdown || 'No report generated yet.'}</pre>
        </div>

        {/* Footer info */}
        <div className="px-5 py-2.5 border-t border-zinc-800 bg-[#171a22] flex items-center justify-between text-[11px] text-zinc-500 font-mono">
          <span>Generated by Second Opinion Ground-Truth Audit Pipeline</span>
          <span>Markdown GFM format</span>
        </div>
      </div>
    </div>
  );
};
